//! Strict, privacy-minimal shapes for durable DNS event ingestion and reads.
//!
//! Every struct rejects unknown fields. The worker may report only a bounded
//! DNS observation: a query name, DNS metadata and an allow/deny decision. It
//! cannot carry a person id, a verified/enforced flag, a URL, a path, a body,
//! a header or a secret. Server-owned fields (household, gateway, receipt,
//! received time) come from the authenticated credential and the server clock.

use std::collections::HashSet;

use chrono::{DateTime, Duration as ChronoDuration, Utc};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use uuid::Uuid;

use crate::error::{ApiError, ApiResult};

/// Maximum events in one accepted batch and the matching database CHECK.
pub const MAX_EVENTS_PER_BATCH: usize = 256;
/// Body cap applied as an axum layer before deserialization.
pub const MAX_REQUEST_BYTES: usize = 256 * 1024;
pub const MAX_NAME_LEN: usize = 253;
pub const MAX_REASON_LEN: usize = 64;
pub const MAX_TEXT_LEN: usize = 200;
pub const MAX_ID_LEN: usize = 64;
pub const MAX_QUERY_TYPE_LEN: usize = 8;
pub const MAX_PROTOCOL_LEN: usize = 12;
/// Worker-reported occurrence time window.
pub const MAX_FUTURE_SKEW: ChronoDuration = ChronoDuration::seconds(60);
pub const MAX_OBSERVATION_AGE: ChronoDuration = ChronoDuration::days(30);
/// Read bounds.
pub const MAX_PAGE_LIMIT: u32 = 200;
pub const MAX_OFFSET: u32 = 100_000;
pub const MAX_TOP_N: usize = 20;

const QUERY_TYPES: &[&str] = &[
    "A", "AAAA", "CNAME", "SOA", "TXT", "MX", "SRV", "NS", "PTR", "CAA", "SVCB", "HTTPS", "DNAME",
    "DS", "DNSKEY", "ANY",
];
const PROTOCOLS: &[&str] = &[
    "udp", "tcp", "dot", "doh", "doq", "dnscrypt", "h3", "unknown",
];
const CACHE_STATES: &[&str] = &["hit", "miss", "stale", "bypass", "unknown"];
const SECRET_MARKERS: &[&str] = &[
    "password",
    "passwd",
    "secret",
    "token",
    "api_key",
    "apikey",
    "authorization",
    "bearer ",
    "cookie",
    "credential",
    "private_key",
    "session_id",
];

fn bad(message: &'static str) -> ApiError {
    ApiError::bad_request(message)
}

/// A domain-shaped, privacy-clean token. Never a URL, path, query string or
/// credential. This is the single gate for all free-text fields.
fn clean_token(value: &str, max: usize, allow_dot: bool) -> bool {
    if value.is_empty() || value.len() > max || value.chars().any(char::is_control) {
        return false;
    }
    let lower = value.to_ascii_lowercase();
    if lower.contains("://")
        || lower.contains('@')
        || lower.contains('?')
        || lower.contains('#')
        || lower.contains("..")
    {
        return false;
    }
    if SECRET_MARKERS.iter().any(|m| lower.contains(m)) {
        return false;
    }
    if allow_dot {
        // Query names use letters, digits, hyphen, underscore and dots. A
        // trailing root dot is accepted and normalised away by the caller.
        value
            .trim_end_matches('.')
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_' || b == b'.')
    } else {
        true
    }
}

/// Normalise a query name and reject any URL/secret-shaped input.
pub fn normalize_domain(value: &str) -> ApiResult<String> {
    let trimmed = value.trim();
    if !clean_token(trimmed, MAX_NAME_LEN, true) {
        return Err(bad("invalid DNS query name"));
    }
    let normalized = trimmed.trim_end_matches('.').to_ascii_lowercase();
    if normalized.is_empty() {
        return Err(bad("invalid DNS query name"));
    }
    Ok(normalized)
}

/// Bounded opaque token (reason code, applied rule, upstream label, source id).
pub fn normalize_text(value: &str, max: usize, field: &'static str) -> ApiResult<String> {
    if !clean_token(value.trim(), max, false) {
        return Err(bad(field));
    }
    Ok(value.trim().to_string())
}

